import SwiftUI

struct ReceiptDocumentView: View {
    @Environment(\.palette) private var palette
    let booking: Booking
    let renterName: String
    let ownerName: String

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            Text("SakayNa")
                .font(.system(size: 18, weight: .heavy))
                .foregroundStyle(palette.text)
            row("Booking ID", booking.id)
            row("Renter", renterName)
            row("Owner", ownerName)
            row("Vehicle", booking.vehicle.name)
            row(
                "Dates",
                "\(AppFormat.longDate(booking.startDate)) — \(AppFormat.longDate(booking.endDate))"
            )
            row("Rate", "\(AppFormat.peso(booking.vehicle.pricePerDay)) × \(booking.days) day\(booking.days == 1 ? "" : "s")")
            if booking.approvedExtraDays > 0 {
                row(
                    "Extension",
                    "+\(booking.approvedExtraDays) day\(booking.approvedExtraDays == 1 ? "" : "s")"
                )
            }
            row("Add-ons", AppFormat.peso(booking.addonPrice * booking.days))
            row("Deposit", AppFormat.peso(booking.deposit))
            ForEach(booking.depositDeductions) { item in
                row("Deduction: \(item.reason)", AppFormat.peso(item.amount))
            }
            row("Deposit refund", AppFormat.peso(booking.depositRefund))
            if booking.lateReturnFee > 0 {
                row(
                    "Late return (\(booking.extraLateDays) extra day\(booking.extraLateDays == 1 ? "" : "s"))",
                    AppFormat.peso(booking.lateReturnFee)
                )
            } else {
                row("Late return fee", AppFormat.peso(0))
            }
            Divider().overlay(palette.border)
            HStack {
                Text("Total")
                    .font(.system(size: 16, weight: .semibold))
                Spacer()
                Text(AppFormat.peso(booking.totalPrice + booking.lateReturnFee))
                    .font(.system(size: 16, weight: .heavy))
            }
            .foregroundStyle(palette.text)
            row("Payment method", booking.paymentMethod.rawValue)
            row("Payment status", booking.currentPaymentStatus.rawValue)
            if let reference = booking.paymentReference, !reference.isEmpty {
                row("Payment reference", reference)
            }
            Text("Generated by SakayNa")
                .font(.system(size: 11))
                .foregroundStyle(palette.muted)
                .frame(maxWidth: .infinity)
                .padding(.top, 8)
        }
    }

    private func row(_ label: String, _ value: String) -> some View {
        HStack(alignment: .top) {
            Text(label)
                .font(.system(size: 13))
                .foregroundStyle(palette.muted)
            Spacer()
            Text(value)
                .font(.system(size: 13, weight: .medium))
                .foregroundStyle(palette.text)
                .multilineTextAlignment(.trailing)
        }
    }
}
